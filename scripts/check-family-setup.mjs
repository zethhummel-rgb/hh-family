import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../src/familySetup.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {queueFamilySetup,familySetupProgress,saveFamilySetupStep,finishFamilySetup}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const data=new Map(),store={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};
assert.equal(familySetupProgress('owner','home',store),null,'Existing homes do not get an automatic setup prompt');
queueFamilySetup('owner','home',store);
assert.deepEqual(familySetupProgress('owner','home',store),{step:'palette',paletteFirst:true},'New owners choose their palette first');
assert.equal(familySetupProgress('other','home',store),null,'Setup belongs to its creator');
assert.equal(familySetupProgress('owner','other-home',store),null,'Setup belongs to its household');
for(const step of ['profiles','palette','email']){
 const progress={step,paletteFirst:true};
 saveFamilySetupStep('owner','home',progress,store);
 assert.deepEqual(familySetupProgress('owner','home',store),progress,'A reload resumes the selected setup step');
}
finishFamilySetup('owner','home',store);
assert.equal(familySetupProgress('owner','home',store),null,'Done or dismissal stops automatic reopening');
store.setItem('hh:family-setup:v1:owner:home','profiles');
assert.deepEqual(familySetupProgress('owner','home',store),{step:'profiles',paletteFirst:false},'An older setup resumes in its original order');
saveFamilySetupStep('owner','home',{step:'palette',paletteFirst:false},store);
assert.deepEqual(familySetupProgress('owner','home',store),{step:'palette',paletteFirst:false},'An older setup can finish at the palette');
finishFamilySetup('owner','home',store);
assert.equal(familySetupProgress('owner','home',store),null);
const denied={getItem:()=>{throw Error('Denied')},setItem:()=>{throw Error('Denied')},removeItem:()=>{throw Error('Denied')}};
assert.doesNotThrow(()=>queueFamilySetup('owner','home',denied));
assert.doesNotThrow(()=>saveFamilySetupStep('owner','home',{step:'palette',paletteFirst:true},denied));
assert.equal(familySetupProgress('owner','home',denied),null);
assert.doesNotThrow(()=>finishFamilySetup('owner','home',denied));
console.log('Family setup checks passed: new-owner trigger, per-home/account isolation, all three resume points, dismissal and unavailable storage.');
