import fs from 'node:fs';import ts from 'typescript';import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../src/loginStorage.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {createLoginStorage,safeStorage,rememberedAuthKey}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const store=()=>{const data=new Map();return {data,getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,value),removeItem:key=>data.delete(key)}};
const local=store(),tab=store();let sequence=0;
const make=(visit=tab)=>createLoginStorage(()=>local,()=>visit,()=>String(++sequence));
let login=make();assert.equal(login.remember,true);
let options=login.options();assert.equal(options.storageKey,rememberedAuthKey);
options.storage.setItem(options.storageKey,'remembered-session');
assert.equal(make().options().storage.getItem(rememberedAuthKey),'remembered-session','Existing remembered logins survive reloads');
login.select(false);options=login.options();const visitKey=options.storageKey;
assert.notEqual(visitKey,rememberedAuthKey);
options.storage.setItem(visitKey,'visit-session');
assert.equal(local.getItem(visitKey),null,'A visit-only credential never reaches local storage');
assert.equal(local.getItem(rememberedAuthKey),'remembered-session','Choosing visit-only does not erase another stored session');
login=make();assert.equal(login.remember,false);assert.equal(login.options().storageKey,visitKey);
assert.equal(login.options().storage.getItem(visitKey),'visit-session','The current tab survives a reload');
const otherTab=make(store());assert.equal(otherTab.remember,false);
assert.notEqual(otherTab.options().storageKey,visitKey,'Separate tabs have separate auth broadcast channels');
assert.equal(otherTab.options().storage.getItem(otherTab.options().storageKey),null);
login.options().storage.removeItem(visitKey);assert.equal(make().options().storage.getItem(visitKey),null,'Sign-out clears visit storage');
login.select(true);assert.equal(login.options().storageKey,rememberedAuthKey);
assert.equal(otherTab.remember,false,'A choice in another tab does not change an active visit');
login.options().storage.removeItem(rememberedAuthKey);
assert.equal(make(store()).options().storage.getItem(rememberedAuthKey),null,'Sign-out does not resurrect a remembered session');
local.setItem('sb-ybizqfghnplcxlmlhvyn-auth-token','personal-app-session');
login.select(false);login.options().storage.setItem(login.options().storageKey,'hh-only');
assert.equal(local.getItem('sb-ybizqfghnplcxlmlhvyn-auth-token'),'personal-app-session','The personal app storage stays separate');

const blocked=()=>{throw Error('Storage blocked')};
const privateVisit=createLoginStorage(blocked,blocked,()=> 'private');
privateVisit.options().storage.setItem(rememberedAuthKey,'memory-only');
assert.equal(privateVisit.options().storage.getItem(rememberedAuthKey),'memory-only');
assert.match(privateVisit.warning(),/could not save/);
privateVisit.select(false);privateVisit.options().storage.setItem(privateVisit.options().storageKey,'private-visit');
assert.match(privateVisit.warning(),/could not keep/);
privateVisit.options().storage.removeItem(privateVisit.options().storageKey);
assert.equal(privateVisit.options().storage.getItem(privateVisit.options().storageKey),null);
let notifications=0;
const full=safeStorage(()=>({getItem:()=> 'stale',setItem(){throw Error('Full')},removeItem(){throw Error('Blocked')}}),()=>notifications++);
full.setItem('auth','rotated');assert.equal(full.getItem('auth'),'rotated','A failed write cannot return a stale refresh token');
full.removeItem('auth');assert.equal(full.getItem('auth'),null);assert.equal(notifications,1);
const silent=safeStorage(()=>({getItem:()=> 'stale',setItem(){},removeItem(){}}));
silent.setItem('auth','fresh');assert.equal(silent.getItem('auth'),'fresh');assert.equal(silent.failed,true);
silent.removeItem('auth');assert.equal(silent.getItem('auth'),null,'Silent failures do not bring back a signed-out session');
console.log('Login storage checks passed: remembered reloads, visit-only reloads and tab isolation, real choice changes, sign-out, personal-app separation, blocked/full/silent storage and stale-token prevention. No backend calls.');
